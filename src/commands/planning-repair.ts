// gsdt-planning-repair — port of bin/gsdt-planning-repair. Launcher:
// bin/gsdt-planning-repair → src/launch.mjs planning-repair. The engine is
// src/planning.ts (was lib/gsd_planning.py).
import { spawnSync } from 'node:child_process';
import { isDir, isFile } from '../common.ts';
import { repairDir } from '../planning.ts';

// What `gsdt-planning-repair --help` prints: the comment block at the top of
// the bash script, "# " stripped. Kept verbatim.
export const HELP = `

gsdt-planning-repair — reconcile .planning/ROADMAP.md + STATE.md and recompute
their derived counters from ground truth.

The union merge strategy on these files is right for append-only content and
wrong for every line that is a single source of truth: when a phase branch
flips a line the base branch also changed, union keeps BOTH sides and the file
starts claiming a phase is simultaneously complete and not started. This
collapses those lines back to one value, and recomputes the counters — which
cannot be fixed by picking a side, because after a real phase-11 merge NEITHER
frontmatter block was right (30/12/96 vs 28/11/103; the truth was 30/13/111).

Counters are recomputed from:
  phases   .planning/ROADMAP.md — '### Phase N' headings ∪ '- [x] **Phase N'
  plans    .planning/phases/*/*-PLAN.md
  summaries .planning/phases/*/*-SUMMARY.md

STATE.md's "## Session Continuity" section is never touched: its
'Last session:' / 'Stopped at:' / 'Resume file:' lines are one entry per past
session and legitimately repeat, so every single-value dedupe is scoped to the
block that owns the field.

Idempotent — running it twice changes nothing the second time.

Usage:
  gsdt-planning-repair [--check] [--commit] [--repo <path>]

Options:
  --check        report only, change nothing. Exits 1 if union-merge damage is
                 present (the CI guard); advisories alone still exit 0.
  --commit       commit the repair if it changed anything (no-op when clean)
  --repo <path>  repo to operate on (default: the checkout containing cwd)
  -h, --help     show this help

WHERE IT RUNS
  gsdt-finish     automatically, after the phase merge and after any
                 origin-sync merge on the push-retry path
  post-merge     the git hook installed by gsdt-bootstrap-repo, so a plain
                 \`git pull\` on the base branch is covered too
  CI             \`gsdt-planning-repair --check\` on the shared branch

RELATED
  gsdt-planning-merge   the merge driver that stops the damage landing at all
`;

/** die() */
class Die extends Error {}
const die = (msg: string): never => {
  throw new Die(`✖ ${msg}\n`);
};

const gitOut = (args: string[]): string => {
  const r = spawnSync('git', args, { encoding: 'utf8', stdio: ['inherit', 'pipe', 'ignore'] });
  return r.status === 0 ? (r.stdout ?? '').replace(/\n+$/, '') : '';
};

const COMMIT_MESSAGE = `docs(gsd): reconcile .planning after union merge

Collapsed the both-sides lines union left behind and recomputed the
progress counters from the roadmap and the plan/summary files on disk.
Generated by gsdt-planning-repair.`;

export function main(argv: string[]): number {
  let check = false;
  let commit = false;
  let repo = '';
  try {
    for (let i = 0; i < argv.length; ) {
      const a = argv[i] as string;
      if (a === '-h' || a === '--help') {
        process.stdout.write(HELP.replace(/^\n/, ''));
        return 0;
      } else if (a === '--check' || a === '-n') {
        check = true;
        i++;
      } else if (a === '--commit') {
        commit = true;
        i++;
      } else if (a === '--repo') {
        if (argv.length - i < 2) die('--repo needs a value');
        repo = argv[i + 1] as string;
        i += 2;
      } else die(`unknown argument: ${a} (see gsdt-planning-repair --help)`);
    }
    if (check && commit) die('--check and --commit are mutually exclusive');

    if (repo === '') {
      repo = gitOut(['rev-parse', '--show-toplevel']);
      if (repo === '') die('not inside a git repository — pass --repo <path>');
    }
    if (!isDir(`${repo}/.planning`)) die(`${repo} has no .planning/ directory`);
    // No roadmap yet (fresh project, or archived): nothing to reconcile, and not
    // merge damage — so not a --check failure either.
    if (!isFile(`${repo}/.planning/ROADMAP.md`)) {
      process.stdout.write('• no .planning/ROADMAP.md — nothing to check\n');
      return 0;
    }
  } catch (e) {
    if (e instanceof Die) {
      process.stderr.write(e.message);
      return 1;
    }
    throw e;
  }

  let rc: number;
  try {
    const r = repairDir(`${repo}/.planning`, check);
    process.stdout.write(r.out);
    process.stderr.write(r.err);
    rc = r.rc;
  } catch (e) {
    process.stderr.write(`gsdt-planning-repair: ${(e as Error).message}\n`);
    rc = 1;
  }

  if (commit && gitOut(['-C', repo, 'status', '--porcelain', '--', '.planning']) !== '') {
    // Stage only what exists: a repo may legitimately have ROADMAP.md without
    // STATE.md, and `git add` on a missing pathspec is fatal.
    const stage = ['.planning/ROADMAP.md', '.planning/STATE.md'].filter((f) => isFile(`${repo}/${f}`));
    // Commit ONLY these two files: anything else the user had staged stays
    // staged and out of the repair commit.
    if (stage.length > 0) {
      const g = (args: string[]): number =>
        spawnSync('git', ['-C', repo, ...args], { stdio: 'inherit' }).status ?? 1;
      if (g(['add', '--', ...stage]) === 0 && g(['diff', '--cached', '--quiet', '--', ...stage]) !== 0) {
        // bash ran under `set -e`: a failed commit ends the script with its status
        const cs = g(['commit', '-q', '-m', COMMIT_MESSAGE, '--', ...stage]);
        if (cs !== 0) return cs;
        process.stdout.write('✔ committed the .planning repair\n');
      }
    }
  }
  return rc;
}
